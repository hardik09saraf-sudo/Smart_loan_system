import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';
import 'firebase_options.dart'; // Auto-generated by 'flutterfire configure'
import 'app.dart'; // Imports our MyApp widget

// 'async' allows us to wait for Firebase to finish connecting before starting the app
void main() async {
  // 1. Makes sure Flutter's engine is ready before calling Firebase
  WidgetsFlutterBinding.ensureInitialized();

  // 2. Connects the app to your Firebase project (Android/iOS/Web settings)
  await Firebase.initializeApp(
    options: DefaultFirebaseOptions.currentPlatform,
  );

  // 3. Launches the main app widget defined in app.dart
  runApp(const MyApp());
}